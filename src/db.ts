import { attachDatabasePool } from "@neon/functions";
import { Pool } from "pg";

import { required } from "./env.js";

const pool = new Pool({
  connectionString: required("DATABASE_URL"),
  max: 5,
});
attachDatabasePool(pool);

export { pool };

const schemaSql = `
CREATE TABLE IF NOT EXISTS cars (
  id integer PRIMARY KEY,
  name text NOT NULL,
  slug text NOT NULL UNIQUE,
  subtitle text,
  photo_url text,
  is_dark_mode boolean NOT NULL DEFAULT false,
  price numeric NOT NULL,
  sort_order integer NOT NULL DEFAULT 0
);

CREATE TABLE IF NOT EXISTS site_content (
  key_name text PRIMARY KEY,
  value text NOT NULL
);

CREATE TABLE IF NOT EXISTS navbar_links (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title text NOT NULL,
  url text NOT NULL,
  sort_order integer NOT NULL DEFAULT 0
);

CREATE TABLE IF NOT EXISTS footer_links (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  category text NOT NULL,
  title text NOT NULL,
  url text NOT NULL,
  sort_order integer NOT NULL DEFAULT 0
);

CREATE TABLE IF NOT EXISTS rentals (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  booking_ref text NOT NULL UNIQUE,
  user_uid text NOT NULL,
  car_name text NOT NULL,
  car_image text,
  start_date text NOT NULL,
  end_date text NOT NULL,
  days integer NOT NULL,
  price numeric NOT NULL,
  status text NOT NULL DEFAULT 'upcoming',
  location text,
  created_at timestamptz NOT NULL DEFAULT now()
);
`;

let ready: Promise<void> | null = null;

export function ensureSchema(): Promise<void> {
  ready ??= (async () => {
    await pool.query(schemaSql);
    const cars = await pool.query("SELECT COUNT(*)::int AS count FROM cars");
    if (cars.rows[0].count === 0) {
      await pool.query(
        `INSERT INTO cars (id, name, slug, subtitle, photo_url, is_dark_mode, price, sort_order)
         VALUES
           (1, 'an RS6', 'an-RS6', 'Rent...', 'assets/WLR_CAR_RS6.png', false, 120, 1),
           (2, 'an EVO', 'an-EVO', 'Rent...', 'assets/WLR_CAR_EVO.png', true, 150, 2)`,
      );
    }
    const content = await pool.query(
      "SELECT COUNT(*)::int AS count FROM site_content",
    );
    if (content.rows[0].count === 0) {
      await pool.query(
        `INSERT INTO site_content (key_name, value) VALUES
           ('footer_brand_desc', 'Welcome to Welrent, the smartest auto sharing and rental app. We guarantee the perfect car for every moment.'),
           ('footer_copyright', '© 2026 Welrent App. Smart Agreements.')`,
      );
    }
    const nav = await pool.query(
      "SELECT COUNT(*)::int AS count FROM navbar_links",
    );
    if (nav.rows[0].count === 0) {
      await pool.query(
        `INSERT INTO navbar_links (title, url, sort_order) VALUES
           ('Welrent Act', '/act', 1),
           ('Locations', '/locations', 2),
           ('Vehicles', '/offerlist', 3)`,
      );
    }
    const footer = await pool.query(
      "SELECT COUNT(*)::int AS count FROM footer_links",
    );
    if (footer.rows[0].count === 0) {
      await pool.query(
        `INSERT INTO footer_links (category, title, url, sort_order) VALUES
           ('Places', 'Rent in Amsterdam', '/locations/amsterdam', 1),
           ('Places', 'All destinations', '/locations', 2),
           ('Special Cars', 'Electric Cars', '/offerlist?type=car', 1),
           ('Special Cars', 'Motorbikes', '/offerlist?type=motorcycle', 2),
           ('Conditions', 'Car agreement (Act)', 'https://act.welrent.com/pages/car-rental-agreement', 1),
           ('Conditions', 'Privacy (Act)', 'https://act.welrent.com/pages/privacy', 2),
           ('Conditions', 'Terms (Act)', 'https://act.welrent.com/pages/terms', 3),
           ('About', 'Welrent Act', '/act', 1),
           ('About', 'Act on GitHub', 'https://github.com/welrent/Act', 2),
           ('About', 'F1 Sponsorship', '/sponsorship/f1/wr/designed', 3)`,
      );
    }
  })();
  return ready;
}
